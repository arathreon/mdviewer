//! Generates the table of embedded third-party browser files (`assets/vendor`).
//!
//! Mermaid alone has more than 100 files, so a list by hand would be error-prone.
//! The output is `$OUT_DIR/vendor_files.rs`, included by `src/assets.rs`.

use std::fs;
use std::path::{Path, PathBuf};

/// The folder of the third-party browser files, relative to the package root.
const VENDOR_DIR: &str = "assets/vendor";

/// The file types that the page uses. Licenses and documentation are not served.
const SERVED_EXTENSIONS: &[&str] = &["js", "mjs", "css", "woff2", "svg"];

fn main() {
    println!("cargo:rerun-if-changed={VENDOR_DIR}");
    let mut files = Vec::new();
    collect(Path::new(VENDOR_DIR), "", &mut files);
    files.sort();

    let mut out = String::from(
        "/// Generated by `build.rs` from `assets/vendor`: (path below `/_mdviewer/`, content).\n\
         pub static VENDOR_FILES: &[(&str, &[u8])] = &[\n",
    );
    for file in &files {
        out.push_str(&format!(
            "    (\"{file}\", include_bytes!(concat!(env!(\"CARGO_MANIFEST_DIR\"), \"/{VENDOR_DIR}/{file}\"))),\n"
        ));
    }
    out.push_str("];\n");

    let out_dir = PathBuf::from(std::env::var("OUT_DIR").expect("cargo sets OUT_DIR"));
    fs::write(out_dir.join("vendor_files.rs"), out).expect("cannot write vendor_files.rs");
}

/// Adds the served files below `dir` to `files`, as paths with `/` relative to the vendor folder.
fn collect(dir: &Path, prefix: &str, files: &mut Vec<String>) {
    let entries =
        fs::read_dir(dir).unwrap_or_else(|error| panic!("cannot read {}: {error}", dir.display()));
    for entry in entries {
        let entry = entry.expect("cannot read a folder entry");
        let name = entry
            .file_name()
            .into_string()
            .expect("vendor file names must be UTF-8");
        assert!(
            !name.contains(['"', '\\']),
            "unsupported character in vendor file name {name:?}"
        );
        let relative = format!("{prefix}{name}");
        let path = entry.path();
        if path.is_dir() {
            collect(&path, &format!("{relative}/"), files);
        } else if path
            .extension()
            .and_then(|extension| extension.to_str())
            .is_some_and(|extension| SERVED_EXTENSIONS.contains(&extension))
        {
            files.push(relative);
        }
    }
}
